PRONOUN_SUFFIXES_PAST = [("ت", "I/you"), ("تي", "you f"), ("نا", "we"), ("توا", "you pl")]


# Form II / III verbs: the imperative has no leading alif (كلم، حاول).
NO_ALIF_IMPERATIVE = {"كلم", "فكر", "صدق", "غير", "صور", "جهز", "رتب", "صلح", "شغل", "كمل", "حاول", "ساعد", "سافر", "قابل"}


def sound_forms(he, stem, pres):
    out = [he, he + "ت", he + "وا", stem + "ت", stem + "تي", stem + "نا", stem + "توا"]
    out += ["م" + stem + "تش", "ما" + stem + "تش", "م" + he + "ش", "م" + stem + "ناش", "م" + he + "وش", "م" + stem + "تيش"]
    out += present_forms(pres, plural_drop=False)
    imp = pres if pres[0] in "اأ" or pres in NO_ALIF_IMPERATIVE else "ا" + pres
    out += [imp, imp + "ي", imp + "وا"]
    return out


def doubled_forms(he, stem, pres):
    out = [he, he + "ت", he + "وا", stem + "يت", stem + "يتي", stem + "ينا", stem + "يتوا"]
    out += ["م" + stem + "يتش", "م" + he + "ش", "م" + he + "وش"]
    out += present_forms(pres, plural_drop=False)
    out += [pres, pres + "ي", pres + "وا"]
    return out


def weak_forms(he, stem, pres):
    base = stem[:-1] if stem.endswith("ي") else stem
    out = [he, base + "يت", base + "يتي", base + "ينا", base + "يتوا", he.rstrip("ىي") + "ت", he.rstrip("ىي") + "وا"]
    out += ["م" + base + "يتش", "م" + base + "يناش"]
    root = pres[:-1] if pres[-1] in "ىي" else pres
    for p in ["بي", "بت", "ب", "بن", "هي", "هت", "ه", "هن", "ي", "ت", "ن"]:
        out.append(p + pres)
    for p in ["بي", "بت", "هي", "هت", "ي", "ت"]:
        out.append(p + root + "وا")
    neg = pres[:-1] + "ا" if pres.endswith("ى") else pres   # بينسى → مبينساش
    out += ["مبي" + neg + "ش", "مبت" + neg + "ش", "مب" + neg + "ش"]
    imp = "ا" + root + "ي" if not root.startswith("ا") else root + "ي"
    out += [imp, ("ا" + root if not root.startswith("ا") else root) + "وا"]
    return out


def present_forms(p, plural_drop):
    out = []
    for pre in ["بي", "بت", "ب", "بن", "هي", "هت", "ه", "هن", "ي", "ت", "ن"]:
        out.append(pre + p)
    for pre in ["بي", "بت", "هي", "هت", "ي", "ت"]:
        out.append(pre + p + "وا")
    for pre in ["بت", "هت", "ت"]:
        out.append(pre + p + "ي")
    out += ["مبي" + p + "ش", "مبت" + p + "ش", "مب" + p + "ش", "مبن" + p + "ش"]
    return out


def hollow_forms(he, i_stem, pres, imp):
    short = i_stem[:-1]   # قولت → قول
    out = [he, he + "ت", he + "وا", i_stem, short + "تي", short + "نا", short + "توا"]
    out += ["م" + he + "ش", "م" + i_stem + "ش", "م" + he + "وش"]
    out += present_forms(pres, plural_drop=False)
    out += [imp, imp + "ي", imp + "وا"]
    return out


def main():
    common = []
    for w in COMMON.split():
        if w not in common:
            common.append(w)
    generated = []
    for he, stem, pres, kind in VERBS:
        forms = {"s": sound_forms, "d": doubled_forms, "w": weak_forms}[kind](he, stem, pres)
        generated += forms
    for he, i_stem, pres, imp in HOLLOW:
        generated += hollow_forms(he, i_stem, pres, imp)
    generated += EXTRA_FORMS.split()
    seen = set(common)
    lines = list(common)
    for w in generated:
        if w and w not in seen and all("ء" <= c <= "ي" for c in w):
            seen.add(w)
            lines.append(f"{w} 3")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(common)} common + {len(lines) - len(common)} verb forms → {OUT}")


if __name__ == "__main__":
    main()
